export function formatINR(n) {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(n)
}

export function getProduct(id) {
  return PRODUCTS.find((p) => p.id === id)
}

export function relatedProducts(id, n = 4) {
  const p = getProduct(id)
  if (!p) return PRODUCTS.slice(0, n)
  return PRODUCTS.filter((x) => x.id !== id)
    .sort((a, b) => {
      const as = a.categories.filter((c) => p.categories.includes(c)).length
      const bs = b.categories.filter((c) => p.categories.includes(c)).length
      return bs - as
    })
    .slice(0, n)
}
